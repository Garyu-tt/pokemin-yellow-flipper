static void ysound_reset(YellowSoundtrack* s) {
    if(s) memset(s,0,sizeof(*s));
}
static bool ysound_next(
    YellowSoundtrack* s, uint8_t wanted, uint32_t now, YSoundTone* out) {
    if(!s || !out || wanted==0 || wanted>=sizeof(ysound_tunes)/sizeof(ysound_tunes[0]))
        return false;
    const YSoundTune* t=&ysound_tunes[wanted];
    if(!t->count)return false;
    if(s->track!=wanted) {
        s->track=wanted;s->cursor=0;s->started=false;
    }
    if(!s->started){s->started=true;s->next_change_ms=now;}
    if((int32_t)(now-s->next_change_ms)<0)return false;
    *out=t->tones[s->cursor];
    s->cursor=(uint16_t)((s->cursor+1)%t->count);
    /* Game Boy note_type 12: nominal sixteenth note at source tempo. */
    uint32_t duration=(uint32_t)60000*out->units/(t->tempo*4u);
    if(duration<20u)duration=20u;
    s->next_change_ms=now+duration;
    return true;
}
