uint32_t y_source_growth_threshold(uint8_t dex,uint8_t level) {
 YSourceSpecies p;
 if(!y_source_species(dex,&p)||level>100)return 0;
 if(level<=1)return 0;
 uint32_t cube=(uint32_t)level*level*level;
 if(p.growth==0)return cube;
 if(p.growth==1) {
  int32_t value=(int32_t)(6u*cube/5u)-(int32_t)(15u*level*level)
                +100*(int32_t)level-140;
  return value>0?(uint32_t)value:0;
 }
 if(p.growth==2)return cube*4u/5u;
 if(p.growth==3)return cube*5u/4u;
 return 0;
}
bool y_source_calc_stats(uint8_t dex,uint8_t level,YBattleStats* output) {
 YSourceSpecies p;
 if(!output || !level || level>100 || !y_source_species(dex,&p))return false;
 uint8_t source[5]={p.hp,p.attack,p.defense,p.speed,p.special};
 uint8_t derived[5];
 for(unsigned i=0;i<5;i++) {
  uint32_t raw=((2u*source[i]+15u)*level)/100u;
  raw+=i==0?(uint32_t)level+10u:5u;
  derived[i]=raw>255u?255u:(uint8_t)raw;
 }
 *output=(YBattleStats){derived[0],derived[1],derived[2],derived[3],derived[4]};
 return true;
}
