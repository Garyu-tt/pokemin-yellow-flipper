uint8_t yellow_route3_passable(int x,int y){
    if(x<0||y<0||x>=70||y>=18)return 0;
    unsigned bit=(unsigned)y*70u+(unsigned)x;
    return (uint8_t)((ycollision_route3[bit/8u]>>(bit&7u))&1u);
}
uint8_t yellow_route3_tile_id(int x,int y){
    if(x<0||y<0||x>=140||y>=36)return 0xff;
    uint8_t block=ymap_route3[(y/4)*35+x/4];
    if(block>=128)return 0xff;
    return ypewter_overworld_blocks[(unsigned)block*16u+(y%4)*4u+(x%4)];
}
