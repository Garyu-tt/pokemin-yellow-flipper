uint8_t yellow_route4_passable(int x,int y) {
    if(x<0||y<0||x>=90||y>=18)return 0;
    unsigned bit=(unsigned)y*90u+(unsigned)x;
    return (uint8_t)((ycollision_route4[bit/8u]>>(bit&7u))&1u);
}
uint8_t yellow_route4_tile_id(int x,int y) {
    if(x<0||y<0||x>=180||y>=36)return 0xff;
    uint8_t block=ymap_route4[(y/4)*45+x/4];
    if(block>=128)return 0xff;
    return ypewter_overworld_blocks[(unsigned)block*16u+(y%4)*4u+x%4u];
}
